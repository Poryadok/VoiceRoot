// This independent generated-protobuf path catches hand codec/descriptor drift.
func TestGeneratedConsentMatchesCanonicalCodec(t *testing.T) {
	c := lfpconsent.Consent{
		ConsentID:           uuid.MustParse("00000000-0000-0000-0000-000000000001"),
		ResponseOperationID: uuid.MustParse("00000000-0000-0000-0000-000000000002"),
		StoryID:             uuid.MustParse("00000000-0000-0000-0000-000000000003"),
		StoryIncarnation:    uuid.MustParse("00000000-0000-0000-0000-000000000004"),
		OfferRevision:       7, AuthorProfileID: uuid.MustParse("00000000-0000-0000-0000-000000000005"),
		ResponderAccountID:    uuid.MustParse("00000000-0000-0000-0000-000000000006"),
		ResponderProfileID:    uuid.MustParse("00000000-0000-0000-0000-000000000007"),
		ResponderSessionEpoch: 9, ResponseType: lfpconsent.Join,
		CriteriaSHA256: [32]byte{1}, OfferPayloadSHA256: [32]byte{2},
		CreatedAtUnixMillis: 1000, OfferExpiresAtUnixMillis: 2000, PrincipalRequestSHA256: [32]byte{3},
	}
	for _, response := range []uint64{lfpconsent.Join, lfpconsent.Invite} {
		c.ResponseType = response
		b, h, err := lfpconsent.Encode(c)
		if err != nil {
			t.Fatal(err)
		}
		m := &storyv1.LfpConsentMaterial{
			ProtocolVersion: 1, ConsentId: c.ConsentID[:], ResponseOperationId: c.ResponseOperationID[:],
			StoryId: c.StoryID[:], StoryIncarnation: c.StoryIncarnation[:], OfferRevision: c.OfferRevision,
			AuthorProfileId: c.AuthorProfileID[:], ResponderAccountId: c.ResponderAccountID[:], ResponderProfileId: c.ResponderProfileID[:],
			ResponderSessionEpoch: c.ResponderSessionEpoch, ResponseType: storyv1.LfpConsentResponseType(response),
			CriteriaSha256: c.CriteriaSHA256[:], OfferPayloadSha256: c.OfferPayloadSHA256[:],
			CreatedAtUnixMillis: c.CreatedAtUnixMillis, OfferExpiresAtUnixMillis: c.OfferExpiresAtUnixMillis,
			PrincipalRequestSha256: c.PrincipalRequestSHA256[:],
		}
		generated, err := (proto.MarshalOptions{Deterministic: true}).Marshal(m)
		if err != nil || !bytes.Equal(b, generated) {
			t.Fatalf("generated wire differs: %v", err)
		}
		got, gh, err := lfpconsent.Decode(generated)
		if err != nil || got != c || gh != h {
			t.Fatalf("generated roundtrip: %v", err)
		}
	}
}

func TestGeneratedRegistrationMatchesCanonicalCodec(t *testing.T) {
	r := lfpconsent.Registration{
		OperationID:   uuid.MustParse("00000000-0000-0000-0000-000000000001"),
		ConsentID:     uuid.MustParse("00000000-0000-0000-0000-000000000002"),
		ConsentSHA256: [32]byte{1}, RegistrationID: uuid.MustParse("00000000-0000-0000-0000-000000000003"),
		Generation: 4, CapturedSearchIntentSHA256: [32]byte{2},
	}
	b, h, e := lfpconsent.EncodeRegistration(r)
	if e != nil {
		t.Fatal(e)
	}
	// Hash field8 MUST be absent from its own input.
	m := &storyv1.LfpConsentRegistration{ProtocolVersion: 1, RegistrationOperationId: r.OperationID[:], ConsentId: r.ConsentID[:], ConsentSha256: r.ConsentSHA256[:], RegistrationId: r.RegistrationID[:], RegistrationGeneration: r.Generation, CapturedSearchIntentSha256: r.CapturedSearchIntentSHA256[:]}
	generated, e := (proto.MarshalOptions{Deterministic: true}).Marshal(m)
	if e != nil || !bytes.Equal(b, generated) {
		t.Fatalf("registration generated bytes differ: %v", e)
	}
	got, gh, e := lfpconsent.DecodeRegistration(generated)
	if e != nil || got != r || gh != h {
		t.Fatalf("registration generated roundtrip: %v", e)
	}
	m.RegistrationSha256 = h[:]
	selfHashed, e := (proto.MarshalOptions{Deterministic: true}).Marshal(m)
	if e != nil {
		t.Fatal(e)
	}
	if _, _, e := lfpconsent.DecodeRegistration(selfHashed); e == nil {
		t.Fatal("self hash field cannot enter material")
	}
}
