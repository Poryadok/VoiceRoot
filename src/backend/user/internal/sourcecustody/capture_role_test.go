func isolateWriterDatabases(t *testing.T, root *pgxpool.Pool, target string) {
	t.Helper()
	rows, err := root.Query(context.Background(), `SELECT datname FROM pg_database WHERE datallowconn AND datname<>$1`, target)
	require.NoError(t, err)
	var names []string
	for rows.Next() {
		var name string
		require.NoError(t, rows.Scan(&name))
		names = append(names, name)
	}
	require.NoError(t, rows.Err())
	rows.Close()
	for _, name := range names {
		_, err = root.Exec(context.Background(), `REVOKE CONNECT ON DATABASE `+pgx.Identifier{name}.Sanitize()+` FROM PUBLIC`)
		require.NoError(t, err)
	}
}

func TestPhysicalCaptureWithNonSuperuserRole(t *testing.T) {
	ctx := context.Background()
	root := custodyDatabase(t, ctx)
	t.Setenv("USER_ASSOCIATION_TEST_DSN", root.Config().ConnString())
	db := associationfixture.New(t, 1)
	receipt, err := associationfixture.ReadInstallerReceipt(db.InstallerReceiptPath)
	require.NoError(t, err)
	fingerprint := sha256.Sum256(receipt.UserKey)
	keys, err := identityassociation.NewKeyset(identityassociation.KeysetSnapshot{Revision: 1, ActiveVersion: receipt.KeyVersion, Versions: map[uint32][32]byte{receipt.KeyVersion: fingerprint}}, map[uint32][]byte{receipt.KeyVersion: receipt.UserKey})
	require.NoError(t, err)
	owner, err := identityassociation.NewStore(db.Pool, keys, receipt.HistoryGeneration)
	require.NoError(t, err)
	require.NoError(t, owner.Bootstrap(ctx))
	require.NoError(t, owner.ActivateGuards(ctx))
	var physical identityassociation.PhysicalSourceIdentity
	require.NoError(t, db.Pool.QueryRow(ctx, `SELECT system_identifier::text,current_database(),(SELECT oid FROM pg_database WHERE datname=current_database()) FROM pg_control_system()`).Scan(&physical.SystemIdentifier, &physical.Database, &physical.DatabaseOID))
	_, err = root.Exec(ctx, `CREATE ROLE custody_app LOGIN PASSWORD 'fixture_only'`)
	require.NoError(t, err)
	_, err = root.Exec(ctx, `REVOKE CONNECT ON DATABASE `+pgx.Identifier{physical.Database}.Sanitize()+` FROM PUBLIC`)
	require.NoError(t, err)
	_, err = db.Pool.Exec(ctx, `REVOKE EXECUTE ON FUNCTION pg_catalog.pg_control_system() FROM PUBLIC`)
	require.NoError(t, err)
	_, err = root.Exec(ctx, `GRANT CONNECT ON DATABASE `+pgx.Identifier{physical.Database}.Sanitize()+` TO custody_app`)
	require.NoError(t, err)
	_, err = db.Pool.Exec(ctx, `GRANT USAGE ON SCHEMA public TO custody_app;
GRANT SELECT,INSERT,UPDATE,DELETE ON ALL TABLES IN SCHEMA public TO custody_app;
GRANT USAGE,SELECT,UPDATE ON ALL SEQUENCES IN SCHEMA public TO custody_app;
GRANT EXECUTE ON ALL FUNCTIONS IN SCHEMA public TO custody_app`)
	require.NoError(t, err)
	config := db.Pool.Config().Copy()
	config.ConnConfig.User = "custody_app"
	config.ConnConfig.Password = "fixture_only"
	app, err := pgxpool.NewWithConfig(ctx, config)
	require.NoError(t, err)
	defer app.Close()
	var actualUser string
	var superuser bool
	require.NoError(t, app.QueryRow(ctx, `SELECT current_user,(SELECT rolsuper FROM pg_roles WHERE rolname=current_user)`).Scan(&actualUser, &superuser))
	require.Equal(t, "custody_app", actualUser)
	require.False(t, superuser)
	store, err := identityassociation.NewStore(app, keys, receipt.HistoryGeneration)
	require.NoError(t, err)
	digest, err := keys.CustodyDigest()
	require.NoError(t, err)
	_, err = store.CaptureProfilesForPhysicalSource(ctx, db.Profiles, receipt.HistoryGeneration, receipt.UserSourceGeneration, digest, physical)
	require.Error(t, err, "source identity must not be guessed when the role cannot read it")
	pin := PhysicalSource{SystemIdentifier: physical.SystemIdentifier, Database: physical.Database, DatabaseOID: physical.DatabaseOID}
	require.Error(t, CheckWriterConfinement(ctx, db.Pool, pin, "custody_app"), "the actual source role must be able to verify its physical connection")
	_, err = db.Pool.Exec(ctx, `GRANT EXECUTE ON FUNCTION pg_catalog.pg_control_system() TO custody_app`)
	require.NoError(t, err)
	require.Error(t, CheckWriterConfinement(ctx, db.Pool, pin, "custody_app"), "writer access to other databases must be excluded")
	isolateWriterDatabases(t, root, physical.Database)
	require.NoError(t, CheckWriterConfinement(ctx, db.Pool, pin, "custody_app"))
	require.Error(t, CheckDormantWriterConfinement(ctx, db.Pool, pin, "custody_app"))
	_, err = root.Exec(ctx, `ALTER ROLE custody_app NOLOGIN`)
	require.NoError(t, err)
	var stillConnected int
	require.NoError(t, app.QueryRow(ctx, `SELECT 1`).Scan(&stillConnected), "NOLOGIN does not fence an already authenticated session")
	require.Error(t, CheckWriterConfinement(ctx, db.Pool, pin, "custody_app"))
	require.NoError(t, CheckDormantWriterConfinement(ctx, db.Pool, pin, "custody_app"))
	_, err = root.Exec(ctx, `ALTER ROLE custody_app LOGIN`)
	require.NoError(t, err)
	_, err = root.Exec(ctx, `GRANT CONNECT ON DATABASE postgres TO custody_app`)
	require.NoError(t, err)
	require.Error(t, CheckWriterConfinement(ctx, db.Pool, pin, "custody_app"))
	_, err = root.Exec(ctx, `REVOKE CONNECT ON DATABASE postgres FROM custody_app`)
	require.NoError(t, err)
	_, err = root.Exec(ctx, `ALTER ROLE custody_app SUPERUSER`)
	require.NoError(t, err)
	require.Error(t, CheckWriterConfinement(ctx, db.Pool, pin, "custody_app"))
	_, err = root.Exec(ctx, `ALTER ROLE custody_app NOSUPERUSER`)
	require.NoError(t, err)
	_, err = root.Exec(ctx, `GRANT CREATE ON DATABASE `+pgx.Identifier{physical.Database}.Sanitize()+` TO custody_app`)
	require.NoError(t, err)
	require.Error(t, CheckWriterConfinement(ctx, db.Pool, pin, "custody_app"))
	_, err = root.Exec(ctx, `REVOKE CREATE ON DATABASE `+pgx.Identifier{physical.Database}.Sanitize()+` FROM custody_app`)
	require.NoError(t, err)
	_, err = db.Pool.Exec(ctx, `GRANT TRUNCATE ON TABLE profiles TO custody_app`)
	require.NoError(t, err)
	require.Error(t, CheckWriterConfinement(ctx, db.Pool, pin, "custody_app"))
	_, err = db.Pool.Exec(ctx, `REVOKE TRUNCATE ON TABLE profiles FROM custody_app`)
	require.NoError(t, err)
	_, err = db.Pool.Exec(ctx, `GRANT TRIGGER ON TABLE profiles TO custody_app`)
	require.NoError(t, err)
	require.Error(t, CheckWriterConfinement(ctx, db.Pool, pin, "custody_app"))
	_, err = db.Pool.Exec(ctx, `REVOKE TRIGGER ON TABLE profiles FROM custody_app`)
	require.NoError(t, err)
	_, err = root.Exec(ctx, `GRANT SET ON PARAMETER session_replication_role TO custody_app`)
	require.NoError(t, err)
	unsafeTx, err := app.Begin(ctx)
	require.NoError(t, err)
	_, err = unsafeTx.Exec(ctx, `SET LOCAL session_replication_role=replica`)
	require.NoError(t, err)
	_, err = unsafeTx.Exec(ctx, `INSERT INTO profiles(account_id,username,discriminator,display_name) VALUES(gen_random_uuid(),'unguarded','1234','Must roll back')`)
	require.NoError(t, err, "the grant can bypass the guarded birth trigger")
	require.NoError(t, unsafeTx.Rollback(ctx))
	require.Error(t, CheckWriterConfinement(ctx, db.Pool, pin, "custody_app"), "the writer must not disable ordinary identity triggers")
	_, err = root.Exec(ctx, `REVOKE SET ON PARAMETER session_replication_role FROM custody_app`)
	require.NoError(t, err)
	_, err = root.Exec(ctx, `GRANT ALTER SYSTEM ON PARAMETER work_mem TO custody_app`)
	require.NoError(t, err)
	require.Error(t, CheckWriterConfinement(ctx, db.Pool, pin, "custody_app"))
	_, err = root.Exec(ctx, `REVOKE ALTER SYSTEM ON PARAMETER work_mem FROM custody_app`)
	require.NoError(t, err)
	_, err = db.Pool.Exec(ctx, `GRANT EXECUTE ON FUNCTION pg_catalog.pg_read_file(text) TO custody_app`)
	require.NoError(t, err)
	var versionFile string
	require.NoError(t, app.QueryRow(ctx, `SELECT pg_catalog.pg_read_file('PG_VERSION')`).Scan(&versionFile))
	require.NotEmpty(t, versionFile)
	require.Error(t, CheckWriterConfinement(ctx, db.Pool, pin, "custody_app"), "direct grants to server-file functions must be rejected")
	_, err = db.Pool.Exec(ctx, `REVOKE EXECUTE ON FUNCTION pg_catalog.pg_read_file(text) FROM custody_app`)
	require.NoError(t, err)
	var restrictedFunction string
	require.NoError(t, db.Pool.QueryRow(ctx, `SELECT p.oid::regprocedure::text FROM pg_proc p JOIN pg_namespace n ON n.oid=p.pronamespace WHERE n.nspname='pg_catalog' AND p.prokind='f' AND p.proname NOT IN ('pg_control_system','pg_read_file','pg_read_binary_file','pg_ls_dir','pg_stat_file','pg_ls_logdir','pg_ls_waldir','pg_ls_archive_statusdir','pg_ls_tmpdir','pg_ls_replslotdir','pg_ls_logicalmapdir','pg_ls_logicalsnapdir','lo_import','lo_export','pg_reload_conf','pg_rotate_logfile','pg_promote','pg_create_restore_point','pg_switch_wal','pg_backup_start','pg_backup_stop') AND NOT EXISTS(SELECT 1 FROM aclexplode(COALESCE(p.proacl,acldefault('f',p.proowner))) a WHERE a.grantee=0 AND a.privilege_type='EXECUTE') ORDER BY p.oid LIMIT 1`).Scan(&restrictedFunction))
	_, err = db.Pool.Exec(ctx, `GRANT EXECUTE ON FUNCTION `+restrictedFunction+` TO custody_app`)
	require.NoError(t, err)
	require.Error(t, CheckWriterConfinement(ctx, db.Pool, pin, "custody_app"), "unlisted restricted system-function grants must also be rejected")
	_, err = db.Pool.Exec(ctx, `REVOKE EXECUTE ON FUNCTION `+restrictedFunction+` FROM custody_app`)
	require.NoError(t, err)
	_, err = root.Exec(ctx, `GRANT pg_write_server_files TO custody_app`)
	require.NoError(t, err)
	require.Error(t, CheckWriterConfinement(ctx, db.Pool, pin, "custody_app"))
	_, err = root.Exec(ctx, `REVOKE pg_write_server_files FROM custody_app`)
	require.NoError(t, err)
	_, err = root.Exec(ctx, `CREATE ROLE unexpected_writer LOGIN`)
	require.NoError(t, err)
	_, err = root.Exec(ctx, `GRANT CONNECT ON DATABASE `+pgx.Identifier{physical.Database}.Sanitize()+` TO unexpected_writer`)
	require.NoError(t, err)
	require.Error(t, CheckWriterConfinement(ctx, db.Pool, pin, "custody_app"))
	_, err = root.Exec(ctx, `REVOKE CONNECT ON DATABASE `+pgx.Identifier{physical.Database}.Sanitize()+` FROM unexpected_writer`)
	require.NoError(t, err)
	_, err = root.Exec(ctx, `ALTER ROLE unexpected_writer NOINHERIT; GRANT custody_app TO unexpected_writer`)
	require.NoError(t, err)
	require.Error(t, CheckWriterConfinement(ctx, db.Pool, pin, "custody_app"), "another login must not be able to SET ROLE to the writer")
	_, err = root.Exec(ctx, `REVOKE custody_app FROM unexpected_writer`)
	require.NoError(t, err)
	_, err = root.Exec(ctx, `GRANT CONNECT ON DATABASE `+pgx.Identifier{physical.Database}.Sanitize()+` TO PUBLIC`)
	require.NoError(t, err)
	require.Error(t, CheckWriterConfinement(ctx, db.Pool, pin, "custody_app"))
	_, err = root.Exec(ctx, `REVOKE CONNECT ON DATABASE `+pgx.Identifier{physical.Database}.Sanitize()+` FROM PUBLIC`)
	require.NoError(t, err)
	_, err = root.Exec(ctx, `CREATE ROLE source_owner_fixture NOLOGIN; ALTER ROLE custody_app NOINHERIT; GRANT source_owner_fixture TO custody_app`)
	require.NoError(t, err)
	_, err = db.Pool.Exec(ctx, `ALTER TABLE profiles OWNER TO source_owner_fixture`)
	require.NoError(t, err)
	require.Error(t, CheckWriterConfinement(ctx, db.Pool, pin, "custody_app"), "SET ROLE must not reach an owner even when inheritance is disabled")
	_, err = db.Pool.Exec(ctx, `ALTER TABLE profiles OWNER TO custody_test`)
	require.NoError(t, err)
	_, err = root.Exec(ctx, `REVOKE source_owner_fixture FROM custody_app`)
	require.NoError(t, err)
	_, err = db.Pool.Exec(ctx, `CREATE SCHEMA other_schema; GRANT CREATE ON SCHEMA other_schema TO custody_app`)
	require.NoError(t, err)
	require.Error(t, CheckWriterConfinement(ctx, db.Pool, pin, "custody_app"))
	_, err = db.Pool.Exec(ctx, `REVOKE CREATE ON SCHEMA other_schema FROM custody_app`)
	require.NoError(t, err)
	_, err = db.Pool.Exec(ctx, `CREATE FUNCTION public.fixture_privileged() RETURNS int LANGUAGE sql SECURITY DEFINER AS 'SELECT 1'`)
	require.NoError(t, err)
	require.Error(t, CheckWriterConfinement(ctx, db.Pool, pin, "custody_app"))
	_, err = db.Pool.Exec(ctx, `DROP FUNCTION public.fixture_privileged()`)
	require.NoError(t, err)
	wrongPin := pin
	wrongPin.DatabaseOID++
	require.Error(t, CheckWriterConfinement(ctx, db.Pool, wrongPin, "custody_app"))
	require.NoError(t, CheckWriterConfinement(ctx, db.Pool, pin, "custody_app"))
	out, err := store.CaptureProfilesForPhysicalSource(ctx, db.Profiles, receipt.HistoryGeneration, receipt.UserSourceGeneration, digest, physical)
	require.NoError(t, err)
	require.Equal(t, identityassociation.CaptureAssociated, out.Observations[db.Profiles[0]].Status)
	require.Equal(t, db.Accounts[db.Profiles[0]], out.Observations[db.Profiles[0]].AccountID)
}
